/*!
  \file
  \brief runChunkedSgmvLoraExpandFwd<T, TileOpt>(): fill the GemmUniversal Arguments of the gather /
         scatter grouped GEMM (common/gather_scatter_group_gemm_types.hpp) and drive it through
         GroupGemmLoraFwd, picking the block-2D or the generic weight path. Called from the
         per-(dtype, tile) .cpp files generated by ChunkedSgmvLoraExpandFwd.cmake.
*/

#pragma once

#include <ATen/ATen.h>
#include <torch/all.h>

#include <optional>
#include <sycl/sycl.hpp>

#include "sycl/kernels/lora/collective/xe_gather_scatter_copy.hpp"
#include "sycl/kernels/lora/device/chunked_sgmv_lora_expand_fwd_types.hpp"

namespace chunked_sgmv_lora_expand_fwd_impl {

// Weights sycl-tla's 2D block load can read ([N_total, rank] per adapter).
inline bool expand_weights_block2d_ok(const torch::Tensor& weights) {
  return cutlass::lora::collective::block2d_rows_ok(weights.data_ptr(), weights.size(1), weights.size(2));
}

template <typename T, typename TileOpt, bool BLOCK_B>
inline void launchChunkedSgmvLoraExpand(
    const torch::Tensor& input_x,
    const torch::Tensor& weights,
    torch::Tensor& output,
    const std::optional<torch::Tensor>& base_output,
    const torch::Tensor& slice_offsets_i32,
    const torch::Tensor& seg_indptr_i32,
    const torch::Tensor& weight_indices_i32,
    const torch::Tensor& scalings_f32,
    const int64_t* permutation,
    const int num_slices,
    const int num_segments,
    sycl::queue& queue) {
  namespace collective = cutlass::lora::collective;
  using Gemm = typename TileOpt::template Types<T, BLOCK_B>::Gemm;
  const int N_total = static_cast<int>(weights.size(1));
  const int R = static_cast<int>(weights.size(2));
  // Slice ids share the group id with the segment (see SegmentSliceProblemShape::group_id).
  TORCH_CHECK(
      num_segments < collective::SegmentSliceProblemShape::kMaxSegments && num_slices < 128,
      "chunked_sgmv_lora_expand_fwd: too many segments / slices: ",
      num_segments,
      " / ",
      num_slices);
  const collective::SegmentSliceProblemShape groups{
      num_segments,
      seg_indptr_i32.data_ptr<int32_t>(),
      weight_indices_i32.data_ptr<int32_t>(),
      slice_offsets_i32.data_ptr<int32_t>(),
      num_slices,
      N_total,
      R,
      input_x.size(0)};

  typename Gemm::Arguments args{};
  args.mode = cutlass::gemm::GemmUniversalMode::kGrouped;
  args.problem_shape = groups;
  args.mainloop = {
      reinterpret_cast<const uint16_t*>(input_x.data_ptr()),
      /*a_ld=*/static_cast<int64_t>(num_slices) * R,
      /*a_slice_ld=*/R,  // slice p reads the p-th rank band of x
      reinterpret_cast<const uint16_t*>(weights.data_ptr()),
      permutation,
      // x rows are num_slices * R long: 16-byte aligned when R % 8 == 0 and the base is.
      R % 8 == 0 && collective::aligned16(input_x.data_ptr()),
      groups};
  args.epilogue = {
      reinterpret_cast<uint16_t*>(output.data_ptr()),
      base_output.has_value() ? reinterpret_cast<const uint16_t*>(base_output->data_ptr()) : nullptr,
      scalings_f32.data_ptr<float>(),
      permutation,
      collective::aligned16(output.data_ptr()) &&
          (!base_output.has_value() || collective::aligned16(base_output->data_ptr())),
      groups};

  Gemm launcher;
  cutlass::Status status = launcher.can_implement(args);
  TORCH_CHECK(
      status == cutlass::Status::kSuccess,
      "chunked_sgmv_lora_expand_fwd: can_implement failed: status=",
      cutlassGetStatusString(status));
  // The segment scheduler needs no workspace, so none is allocated.
  TORCH_CHECK(Gemm::get_workspace_size(args) == 0, "chunked_sgmv_lora_expand_fwd: unexpected workspace");
  status = launcher.run(args, nullptr, queue);
  TORCH_CHECK(
      status == cutlass::Status::kSuccess,
      "chunked_sgmv_lora_expand_fwd: run failed: status=",
      cutlassGetStatusString(status));
}

// T: torch storage type (at::Half / at::BFloat16). permutation is logical -> physical, or
// nullptr (rows already grouped by adapter).
template <typename T, typename TileOpt>
inline void runChunkedSgmvLoraExpandFwd(
    const torch::Tensor& input_x,
    const torch::Tensor& weights,
    torch::Tensor& output,
    const std::optional<torch::Tensor>& base_output,
    const torch::Tensor& slice_offsets_i32,
    const torch::Tensor& seg_indptr_i32,
    const torch::Tensor& weight_indices_i32,
    const torch::Tensor& scalings_f32,
    const int64_t* permutation,
    const int num_slices,
    const int num_segments,
    sycl::queue& queue) {
  if (expand_weights_block2d_ok(weights)) {
    launchChunkedSgmvLoraExpand<T, TileOpt, true>(
        input_x,
        weights,
        output,
        base_output,
        slice_offsets_i32,
        seg_indptr_i32,
        weight_indices_i32,
        scalings_f32,
        permutation,
        num_slices,
        num_segments,
        queue);
  } else {
    launchChunkedSgmvLoraExpand<T, TileOpt, false>(
        input_x,
        weights,
        output,
        base_output,
        slice_offsets_i32,
        seg_indptr_i32,
        weight_indices_i32,
        scalings_f32,
        permutation,
        num_slices,
        num_segments,
        queue);
  }
}

}  // namespace chunked_sgmv_lora_expand_fwd_impl
