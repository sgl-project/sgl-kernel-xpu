/*!
  \file
  \brief runChunkedSgmvLoraExpandFwd<T, TileOpt>(): launch the gather-fused
         DPAS expand kernel. Called from the per-(dtype, tile) .cpp files
         generated by ChunkedSgmvLoraExpandFwd.cmake.
*/

#pragma once

#include <ATen/ATen.h>
#include <torch/all.h>

#include <optional>
#include <sycl/sycl.hpp>

#include "sycl/SYCLHelpers.h"
#include "sycl/kernels/lora/common/lora_dpas_primitives.hpp"
#include "sycl/kernels/lora/device/chunked_sgmv_lora_expand_fwd_kernel.hpp"
#include "sycl/kernels/lora/device/chunked_sgmv_lora_expand_fwd_types.hpp"

namespace chunked_sgmv_lora_expand_fwd_impl {

// ALIGNED selects block-read loads (16-byte aligned x / weight rows) or the
// alignment-free per-lane loads; see expand_rows_aligned().
template <typename T, typename TileOpt, bool ALIGNED>
inline void launchChunkedExpandKernel(
    const torch::Tensor& input_x,
    const torch::Tensor& weights,
    torch::Tensor& output,
    const std::optional<torch::Tensor>& base_output,
    const torch::Tensor& slice_offsets_i32,
    const torch::Tensor& seg_indptr_i32,
    const torch::Tensor& weight_indices_i32,
    const torch::Tensor& scalings_f32,
    const int64_t* permutation,
    const int num_slices,
    const int num_segments,
    sycl::queue& queue) {
  static_assert(TileOpt::KB == 16, "the rank-tail path assumes 16-wide k steps");
  using Kernel = ChunkedExpandDpasKernel<lora_dpas::ElemFor<T>, TileOpt::MB, TileOpt::NT, TileOpt::KB, ALIGNED>;
  const int64_t T_rows = input_x.size(0);
  const int N_total = static_cast<int>(weights.size(1));
  const int R = static_cast<int>(weights.size(2));
  const int sgn = TileOpt::SGN;
  const int wg_cols = sgn * TileOpt::NT * 16;
  // Upper bounds (sum_p ceil(size_p / wg_cols) column groups; row tiles over all
  // segments): the kernel resolves slices and segments on device.
  const int64_t col_groups = (N_total + wg_cols - 1) / wg_cols + num_slices;
  const int64_t row_tiles = (T_rows + Kernel::BM - 1) / Kernel::BM + num_segments;
  Kernel kernel{
      reinterpret_cast<const uint16_t*>(input_x.data_ptr()),
      reinterpret_cast<const uint16_t*>(weights.data_ptr()),
      reinterpret_cast<uint16_t*>(output.data_ptr()),
      base_output.has_value() ? reinterpret_cast<const uint16_t*>(base_output->data_ptr()) : nullptr,
      seg_indptr_i32.data_ptr<int32_t>(),
      weight_indices_i32.data_ptr<int32_t>(),
      permutation,
      slice_offsets_i32.data_ptr<int32_t>(),
      scalings_f32.data_ptr<float>(),
      num_segments,
      R,
      N_total,
      num_slices,
      sgn,
      lora_dpas::aligned16(output.data_ptr()) &&
          (!base_output.has_value() || lora_dpas::aligned16(base_output->data_ptr()))};
  sycl_kernel_submit(sycl::range<2>(row_tiles, col_groups * 16 * sgn), sycl::range<2>(1, 16 * sgn), queue, kernel);
}

// The block-read loads need 16-byte aligned x and weight rows: aligned bases and
// rank % 8 == 0 (x rows are num_slices * rank long, weight rows rank long). Output
// and residual rows are alignment-checked per row on device, so N_total and
// slice_offsets are unconstrained.
inline bool expand_rows_aligned(const torch::Tensor& input_x, const torch::Tensor& weights) {
  return weights.size(2) % 8 == 0 && lora_dpas::aligned16(input_x.data_ptr()) &&
         lora_dpas::aligned16(weights.data_ptr());
}

// T: torch storage type (at::Half / at::BFloat16). permutation is logical ->
// physical, or nullptr (rows already grouped by adapter).
template <typename T, typename TileOpt>
inline void runChunkedSgmvLoraExpandFwd(
    const torch::Tensor& input_x,
    const torch::Tensor& weights,
    torch::Tensor& output,
    const std::optional<torch::Tensor>& base_output,
    const torch::Tensor& slice_offsets_i32,
    const torch::Tensor& seg_indptr_i32,
    const torch::Tensor& weight_indices_i32,
    const torch::Tensor& scalings_f32,
    const int64_t* permutation,
    const int num_slices,
    const int num_segments,
    sycl::queue& queue) {
  if (expand_rows_aligned(input_x, weights)) {
    launchChunkedExpandKernel<T, TileOpt, true>(
        input_x,
        weights,
        output,
        base_output,
        slice_offsets_i32,
        seg_indptr_i32,
        weight_indices_i32,
        scalings_f32,
        permutation,
        num_slices,
        num_segments,
        queue);
  } else {
    launchChunkedExpandKernel<T, TileOpt, false>(
        input_x,
        weights,
        output,
        base_output,
        slice_offsets_i32,
        seg_indptr_i32,
        weight_indices_i32,
        scalings_f32,
        permutation,
        num_slices,
        num_segments,
        queue);
  }
}

}  // namespace chunked_sgmv_lora_expand_fwd_impl
