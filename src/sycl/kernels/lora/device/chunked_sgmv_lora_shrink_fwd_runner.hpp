/*!
  \file
  \brief runChunkedSgmvLoraShrinkFwd<T, TileOpt>(): fill the GemmUniversal Arguments of the gather /
         scatter grouped GEMM (common/gather_scatter_group_gemm_types.hpp) and drive it through
         GroupGemmLoraFwd, picking the block-2D or the generic weight path. Called from the
         per-(dtype, tile) .cpp files generated by ChunkedSgmvLoraShrinkFwd.cmake.
*/

#pragma once

#include <ATen/ATen.h>
#include <torch/all.h>

#include <sycl/sycl.hpp>

#include "sycl/kernels/lora/collective/xe_gather_scatter_copy.hpp"
#include "sycl/kernels/lora/device/chunked_sgmv_lora_shrink_fwd_types.hpp"

namespace chunked_sgmv_lora_shrink_fwd_impl {

// Weights sycl-tla's 2D block load can read ([N, input_dim] per adapter).
inline bool shrink_weights_block2d_ok(const torch::Tensor& weights) {
  return cutlass::lora::collective::block2d_rows_ok(weights.data_ptr(), weights.size(1), weights.size(2));
}

template <typename T, typename TileOpt, bool BLOCK_B>
inline void launchChunkedSgmvLoraShrink(
    const torch::Tensor& input_x,
    const torch::Tensor& weights,
    torch::Tensor& output,
    const torch::Tensor& seg_indptr_i32,
    const torch::Tensor& weight_indices_i32,
    const int64_t* permutation,
    const int num_segments,
    sycl::queue& queue) {
  namespace collective = cutlass::lora::collective;
  using Gemm = typename TileOpt::template Types<T, BLOCK_B>::Gemm;
  const int K = static_cast<int>(input_x.size(1));
  const int N = static_cast<int>(weights.size(1));
  TORCH_CHECK(
      num_segments < collective::SegmentSliceProblemShape::kMaxSegments,
      "chunked_sgmv_lora_shrink_fwd: too many segments: ",
      num_segments);
  // One slice: all N columns read all of x.
  const collective::SegmentSliceProblemShape groups{
      num_segments,
      seg_indptr_i32.data_ptr<int32_t>(),
      weight_indices_i32.data_ptr<int32_t>(),
      /*slice_offsets=*/nullptr,
      /*n_slices=*/1,
      N,
      K,
      input_x.size(0)};

  typename Gemm::Arguments args{};
  args.mode = cutlass::gemm::GemmUniversalMode::kGrouped;
  args.problem_shape = groups;
  args.mainloop = {
      reinterpret_cast<const uint16_t*>(input_x.data_ptr()),
      /*a_ld=*/K,
      /*a_slice_ld=*/0,
      reinterpret_cast<const uint16_t*>(weights.data_ptr()),
      permutation,
      K % 8 == 0 && collective::aligned16(input_x.data_ptr()),
      groups};
  args.epilogue = {reinterpret_cast<uint16_t*>(output.data_ptr()), permutation, groups};

  Gemm launcher;
  cutlass::Status status = launcher.can_implement(args);
  TORCH_CHECK(
      status == cutlass::Status::kSuccess,
      "chunked_sgmv_lora_shrink_fwd: can_implement failed: status=",
      cutlassGetStatusString(status));
  // The segment scheduler needs no workspace, so none is allocated.
  TORCH_CHECK(Gemm::get_workspace_size(args) == 0, "chunked_sgmv_lora_shrink_fwd: unexpected workspace");
  status = launcher.run(args, nullptr, queue);
  TORCH_CHECK(
      status == cutlass::Status::kSuccess,
      "chunked_sgmv_lora_shrink_fwd: run failed: status=",
      cutlassGetStatusString(status));
}

// T: torch storage type (at::Half / at::BFloat16). permutation is logical -> physical, or
// nullptr (rows already grouped by adapter).
template <typename T, typename TileOpt>
inline void runChunkedSgmvLoraShrinkFwd(
    const torch::Tensor& input_x,
    const torch::Tensor& weights,
    torch::Tensor& output,
    const torch::Tensor& seg_indptr_i32,
    const torch::Tensor& weight_indices_i32,
    const int64_t* permutation,
    const int num_segments,
    sycl::queue& queue) {
  if (shrink_weights_block2d_ok(weights)) {
    launchChunkedSgmvLoraShrink<T, TileOpt, true>(
        input_x, weights, output, seg_indptr_i32, weight_indices_i32, permutation, num_segments, queue);
  } else {
    launchChunkedSgmvLoraShrink<T, TileOpt, false>(
        input_x, weights, output, seg_indptr_i32, weight_indices_i32, permutation, num_segments, queue);
  }
}

}  // namespace chunked_sgmv_lora_shrink_fwd_impl
