/*!
  \file
  \brief runChunkedSgmvLoraShrinkFwd<T, TileOpt>(): launch the gather-fused
         DPAS shrink kernel. Called from the per-(dtype, tile) .cpp files
         generated by ChunkedSgmvLoraShrinkFwd.cmake.
*/

#pragma once

#include <ATen/ATen.h>
#include <torch/all.h>

#include <sycl/sycl.hpp>

#include "sycl/SYCLHelpers.h"
#include "sycl/kernels/lora/common/lora_dpas_primitives.hpp"
#include "sycl/kernels/lora/device/chunked_sgmv_lora_shrink_fwd_kernel.hpp"
#include "sycl/kernels/lora/device/chunked_sgmv_lora_shrink_fwd_types.hpp"

namespace chunked_sgmv_lora_shrink_fwd_impl {

// ALIGNED selects block-read loads (16-byte aligned x / weight rows) or the
// alignment-free per-lane loads; see shrink_rows_aligned().
template <typename T, typename TileOpt, bool ALIGNED>
inline void launchChunkedShrinkKernel(
    const torch::Tensor& input_x,
    const torch::Tensor& weights,
    torch::Tensor& output,
    const torch::Tensor& seg_indptr_i32,
    const torch::Tensor& weight_indices_i32,
    const int64_t* permutation,
    const int num_segments,
    sycl::queue& queue) {
  using Kernel = ChunkedShrinkDpasKernel<lora_dpas::ElemFor<T>, TileOpt::MB, TileOpt::NT, TileOpt::KB, ALIGNED>;
  const int64_t T_rows = input_x.size(0);
  const int K = static_cast<int>(input_x.size(1));
  const int N = static_cast<int>(weights.size(1));
  const int n_groups = (N + TileOpt::NT * 16 - 1) / (TileOpt::NT * 16);
  // Upper bound on row tiles; the kernel maps tiles to segments on device and
  // surplus work-groups exit, so no device -> host read of seg_indptr is needed.
  const int64_t row_tiles = (T_rows + Kernel::BM - 1) / Kernel::BM + num_segments;
  const int sgk = TileOpt::SGK;
  Kernel kernel(
      reinterpret_cast<const uint16_t*>(input_x.data_ptr()),
      reinterpret_cast<const uint16_t*>(weights.data_ptr()),
      reinterpret_cast<uint16_t*>(output.data_ptr()),
      seg_indptr_i32.data_ptr<int32_t>(),
      weight_indices_i32.data_ptr<int32_t>(),
      permutation,
      num_segments,
      K,
      N,
      sgk,
      n_groups);
  const int64_t local = 16 * sgk;
  sycl_kernel_submit(row_tiles * n_groups * local, local, queue, kernel);
}

// The block-read loads need every x row and weight row 16-byte aligned: aligned
// bases and a row length (input_dim) that is a multiple of 8 elements.
inline bool shrink_rows_aligned(const torch::Tensor& input_x, const torch::Tensor& weights) {
  return input_x.size(1) % 8 == 0 && lora_dpas::aligned16(input_x.data_ptr()) &&
         lora_dpas::aligned16(weights.data_ptr());
}

// T: torch storage type (at::Half / at::BFloat16). permutation is logical ->
// physical, or nullptr (rows already grouped by adapter).
template <typename T, typename TileOpt>
inline void runChunkedSgmvLoraShrinkFwd(
    const torch::Tensor& input_x,
    const torch::Tensor& weights,
    torch::Tensor& output,
    const torch::Tensor& seg_indptr_i32,
    const torch::Tensor& weight_indices_i32,
    const int64_t* permutation,
    const int num_segments,
    sycl::queue& queue) {
  if (shrink_rows_aligned(input_x, weights)) {
    launchChunkedShrinkKernel<T, TileOpt, true>(
        input_x, weights, output, seg_indptr_i32, weight_indices_i32, permutation, num_segments, queue);
  } else {
    launchChunkedShrinkKernel<T, TileOpt, false>(
        input_x, weights, output, seg_indptr_i32, weight_indices_i32, permutation, num_segments, queue);
  }
}

}  // namespace chunked_sgmv_lora_shrink_fwd_impl
